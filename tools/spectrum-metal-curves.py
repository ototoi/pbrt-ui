#!/usr/bin/env python3
"""Generate the `spectrum` crate's r4 metal curves and D65 table.

Reads pbrt-r4's `src/util/spectrum/named_arrays.rs` (never a build
dependency: this script copies the numbers once and records the r4
commit they were taken at) and writes
`crates/spectrum/src/named_curves.rs`:

- `D65`: CIE standard illuminant D65 at 380–780 nm in 10 nm steps
  (41 samples) — the weights `conductor_f0` integrates the
  per-wavelength Fresnel reflectance against, normalized by the
  D65-weighted luminance (∫ D65·ȳ), as tools/named-metal-f0.py does
  for scene-view's `named_metals.rs` tables.
- `METAL_CURVES`: the r4 named metal eta/k curves
  (`metal-{Ag,Al,Au,Cu,CuZn,MgO,TiO2}-{eta,k}`) as interleaved
  λ/value pairs, piecewise-linear and zero outside their domain, the
  shape r4's `PiecewiseLinearSpectrum` reads.
"""
import argparse
import re
import subprocess
from pathlib import Path

METALS = ("Ag", "Al", "Au", "Cu", "CuZn", "MgO", "TiO2")


def rust_array(source: str, name: str) -> list[float]:
    match = re.search(rf"\b{name}\s*:\s*\[[^]]*\]\s*=\s*\[(.*?)\];", source, re.S)
    if not match:
        raise ValueError(f"could not find Rust array {name}")
    return [
        float(x.replace("_", ""))
        for x in re.findall(
            r"(?<![A-Za-z0-9_])(?:\d+\.\d*|\.\d+|\d+)(?:[eE][+-]?\d+)?",
            match.group(1),
        )
    ]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--r4", type=Path, required=True)
    ap.add_argument(
        "--output",
        type=Path,
        default=Path("crates/spectrum/src/named_curves.rs"),
    )
    args = ap.parse_args()
    source = (args.r4 / "src/util/spectrum/named_arrays.rs").read_text()
    curves = {
        f"metal-{metal}-{kind}": rust_array(source, f"{metal}_{kind}")
        for metal in METALS
        for kind in ("eta", "k")
    }
    for name, pairs in curves.items():
        if not pairs or len(pairs) % 2:
            raise ValueError(f"{name} is not an even, non-empty λ/value list")
    d65_full = rust_array(source, "CIE_Illum_D6500")
    # named_arrays' D65 is an interleaved λ/value list running 300–830 nm
    # at 5 nm steps; the crate's table keeps the values at the
    # 380–780 nm decade points, the wavelengths of CIE_1931.
    d65_samples = list(zip(d65_full[::2], d65_full[1::2]))
    d65 = [
        value
        for wavelength, value in d65_samples
        if wavelength in range(380, 781, 10)
    ]
    if len(d65) != 41:
        raise ValueError(f"D65 decade sampling found {len(d65)} values, not 41")
    commit = subprocess.check_output(
        ["git", "-C", str(args.r4), "rev-parse", "HEAD"], text=True
    ).strip()

    def floats(values: list[float]) -> str:
        columns = 6
        words = [repr(value) for value in values]
        lines = [
            "    " + ", ".join(words[start : start + columns]) + ","
            for start in range(0, len(words), columns)
        ]
        return "\n".join(lines)

    lines = [
        "// Generated by tools/spectrum-metal-curves.py; do not edit.",
        f"// pbrt-r4 commit: {commit}",
        "//! r4's named metal curves and the D65 weights `conductor_f0`",
        "//! integrates against (both copied from pbrt-r4's named_arrays.rs",
        "//! by the generator; pbrt-ui never depends on the r4 crate).",
        "//! The data coincidences (6.28, 3.14, …) are measured values.",
        "#![allow(clippy::approx_constant)]",
        "",
        "/// CIE standard illuminant D65 at 380, 390, … 780 nm — the",
        "/// wavelengths of `CIE_1931`. `conductor_f0` weights each",
        "/// per-wavelength Fresnel reflectance by D65 and normalizes by the",
        "/// integrated D65-weighted luminance ∫ D65·ȳ.",
        "#[rustfmt::skip]",
        "pub(super) const D65: [f64; 41] = [",
        floats(d65),
        "];",
        "",
        "/// The r4 named metal curves (interleaved λ/value samples, ascending",
        "/// λ), read piecewise-linearly with samples outside the curve's",
        "/// domain reading 0, as r4's `PiecewiseLinearSpectrum` does.",
        "#[rustfmt::skip]",
        "pub(super) const METAL_CURVES: &[(&str, &[f64])] = &[",
    ]
    for name in sorted(curves):
        lines.append(f'    ("{name}", &[')
        lines.append(floats(curves[name]))
        lines.append("    ]),")
    lines += [
        "];",
        "",
        "/// One named metal curve's samples, if the table knows the name.",
        "pub(super) fn curve(name: &str) -> Option<&'static [f64]> {",
        "    METAL_CURVES",
        "        .iter()",
        "        .find(|(known, _)| *known == name)",
        "        .map(|(_, samples)| *samples)",
        "}",
        "",
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
