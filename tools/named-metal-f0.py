#!/usr/bin/env python3
"""Generate linear-sRGB normal-incidence F0 for pbrt-v4 named metals.

Two tables: the metal in vacuum (conductor), and the metal under a coat of
index COAT_ETA, where pbrt-v4's coatedconductor divides the metal's eta and
k by the interface eta.
"""
import argparse
import glob
import math
import re
from pathlib import Path


def rust_array(source: str, name: str) -> list[float]:
    match = re.search(rf"\b{name}\s*:\s*\[[^]]*\]\s*=\s*\[(.*?)\];", source, re.S)
    if not match:
        raise ValueError(f"could not find Rust array {name}")
    return [float(x.replace("_", "")) for x in re.findall(r"(?<![A-Za-z0-9_])(?:\d+\.\d*|\.\d+|\d+)(?:[eE][+-]?\d+)?", match.group(1))]


def sample(pairs: list[float], wavelength: float) -> float:
    points = list(zip(pairs[::2], pairs[1::2]))
    if wavelength <= points[0][0] or wavelength >= points[-1][0]:
        return 0.0
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        if x0 <= wavelength <= x1:
            t = (wavelength - x0) / (x1 - x0)
            return y0 + (y1 - y0) * t
    return 0.0


COAT_ETA = 1.5


def parse_array_file(path: Path, names: list[str]) -> dict[str, list[float]]:
    source = path.read_text()
    return {name: rust_array(source, name) for name in names}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--r4", type=Path, required=True)
    ap.add_argument("--output", type=Path, default=Path("crates/scene-view/src/preview/lit/named_metals.rs"))
    args = ap.parse_args()
    named_path = args.r4 / "src/util/spectrum/named_arrays.rs"
    cie_source = (args.r4 / "src/util/spectrum/cie.rs").read_text()
    if not re.search(r'include!\(concat!\(env!\("OUT_DIR"\),\s*"/spectrum_data_cie\.rs"\)\)', cie_source):
        raise SystemExit("r4 cie.rs no longer includes its generated CIE 1931 arrays")
    cie_path = next((Path(p) for p in glob.glob(str(args.r4 / "target/*/build/pbrt-r4-*/out/spectrum_data_cie.rs"))), None)
    if cie_path is None:
        raise SystemExit("build r4 once first; generated spectrum_data_cie.rs not found")
    metal_names = [f"{metal}_{kind}" for metal in ("Cu", "Au", "Ag", "Al") for kind in ("eta", "k")]
    named = parse_array_file(named_path, metal_names + ["CIE_Illum_D6500"])
    cie = parse_array_file(cie_path, ["CIE_X", "CIE_Y", "CIE_Z"])
    def metal_rgb(metal: str, medium: float) -> list[float]:
        xyz = [0.0, 0.0, 0.0]
        norm_y = 0.0
        for wavelength in range(360, 831):
            eta = sample(named[f"{metal}_eta"], wavelength) / medium
            k = sample(named[f"{metal}_k"], wavelength) / medium
            f0 = ((eta - 1) ** 2 + k**2) / ((eta + 1) ** 2 + k**2)
            d65 = sample(named["CIE_Illum_D6500"], wavelength)
            cmfs = [cie[key][wavelength - 360] for key in ("CIE_X", "CIE_Y", "CIE_Z")]
            for i in range(3):
                xyz[i] += f0 * d65 * cmfs[i]
            norm_y += d65 * cmfs[1]
        xyz = [v / norm_y for v in xyz]
        return [3.240479*xyz[0]-1.537150*xyz[1]-0.498535*xyz[2], -0.969256*xyz[0]+1.875991*xyz[1]+0.041556*xyz[2], 0.055648*xyz[0]-0.204043*xyz[1]+1.057311*xyz[2]]

    metals = ("Cu", "Au", "Ag", "Al")
    rgb_rows = [(metal, metal_rgb(metal, 1.0)) for metal in metals]
    coat_rows = [(metal, metal_rgb(metal, COAT_ETA)) for metal in metals]
    commit = __import__("subprocess").check_output(["git", "-C", str(args.r4), "rev-parse", "HEAD"], text=True).strip()
    def table(name: str, doc: str, rows) -> list[str]:
        out = [f"/// {doc}", f"pub(crate) const {name}: [(&str, [f32; 3]); 4] = ["]
        out += [f'    ("{metal}", [{rgb[0]:.9g}, {rgb[1]:.9g}, {rgb[2]:.9g}]),' for metal, rgb in rows]
        return out + ["];"]
    lines = [
        "// Generated by tools/named-metal-f0.py; do not edit.",
        "// pbrt-r4 commit: {commit}".format(commit=commit),
        "// Reference values for the spectrum crate's conductor_f0;",
        "// Lit reads metals through that crate now.",
        "#![allow(dead_code)]",
    ]
    lines += table("NAMED_METALS", "Normal-incidence F0 in vacuum (conductor).", rgb_rows)
    lines += [f"/// Index of the coat `NAMED_METALS_IN_COAT` assumes.", f"pub(crate) const COAT_ETA: f64 = {COAT_ETA};"]
    lines += table("NAMED_METALS_IN_COAT", "F0 under a coat of index COAT_ETA (coatedconductor).", coat_rows)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")

if __name__ == "__main__":
    main()
